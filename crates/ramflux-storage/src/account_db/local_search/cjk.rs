//! Unicode 16 `script/Script_Extensions` union for Han, Hiragana, Katakana and Hangul.
// Scripts.txt SHA256 9e88f0a677df47311106340be8ede2ecdacd9c1c931831218d2be6d5508e0039
// ScriptExtensions.txt SHA256 049117ce26b9769fe2749b06eef51a50a89faef4a97764dd2d81daa715980700

pub(super) fn is_cjk(ch: char) -> bool {
    let value = u32::from(ch);
    RANGES.iter().any(|&(start, end)| (start..=end).contains(&value))
}

