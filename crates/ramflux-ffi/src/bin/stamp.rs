//! Prints the binding API version and descriptor fingerprint as a host source file, so the
//! generated host package records exactly what it was generated from.
//!
//! `ramflux-ffi-stamp swift|kotlin`

use std::process::ExitCode;

fn main() -> ExitCode {
    let version = ramflux_ffi::binding_api_version();
    let fingerprint = ramflux_ffi::descriptor_fingerprint();
    match std::env::args().nth(1).as_deref() {
        Some("swift") => {
            println!("// Generated by ramflux-ffi-stamp. Do not edit.");
            println!("public enum HostBindingStamp {{");
            println!("    public static let apiMajor: UInt32 = {}", version.major);
            println!("    public static let apiMinor: UInt32 = {}", version.minor);
            println!("    public static let descriptorFingerprint = \"{fingerprint}\"");
            println!("}}");
            ExitCode::SUCCESS
        }
        Some("kotlin") => {
            println!("// Generated by ramflux-ffi-stamp. Do not edit.");
            println!("package uniffi.ramflux_ffi");
            println!();
            println!("object HostBindingStamp {{");
            println!("    const val API_MAJOR: Int = {}", version.major);
            println!("    const val API_MINOR: Int = {}", version.minor);
            println!("    const val DESCRIPTOR_FINGERPRINT: String = \"{fingerprint}\"");
            println!("}}");
            ExitCode::SUCCESS
        }
        _ => {
            eprintln!("usage: ramflux-ffi-stamp swift|kotlin");
            ExitCode::from(2)
        }
    }
}
