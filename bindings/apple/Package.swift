// Swift package wrapper around ramflux_ffi.xcframework.
//
// Build the XCFramework and the generated Swift first:
//   bindings/apple/scripts/build-xcframework.sh
// The package has no network dependency and downloads nothing.

import PackageDescription

let package = Package(
    name: "Ramflux",
    platforms: [
        // Keep in step with IPHONEOS_DEPLOYMENT_TARGET in scripts/build-xcframework.sh.
        .iOS(.v16)
    ],
    products: [
        .library(name: "Ramflux", targets: ["Ramflux"])
    ],
    targets: [
        // Static library slices, the C header and the module map generated by UniFFI.
        .binaryTarget(
            name: "ramflux_ffiFFI",
            path: "build/ramflux_ffi.xcframework"
        ),
        // Generated Swift API (Sources/Ramflux/Generated) plus the hand-written helpers that
        // map Swift Task cancellation, the path monitor and the background task onto it.
        .target(
            name: "Ramflux",
            dependencies: ["ramflux_ffiFFI"],
            path: "Sources/Ramflux",
            linkerSettings: [
                .linkedFramework("Security"),
                .linkedFramework("CoreFoundation"),
                .linkedFramework("Network"),
            ]
        ),
    ]
)
