set -euo pipefail
cd "$(dirname "$0")/.."
source_file=crates/ramflux-sdk/src/client/shared_group/bootstrap.rs
named=generated_snapshot_roundtrip_requires_exact_canonical_state_and_seed_grammar
snapshot=$(mktemp)
log_file=$(mktemp)
cp "$source_file" "$snapshot"
restore() { cp "$snapshot" "$source_file"; rm -f "$snapshot" "$log_file"; }
trap restore EXIT
python3 - "$source_file" <<'PY'
from pathlib import Path
import sys
p = Path(sys.argv[1]); s = p.read_text()
old = 'Self::verify_group_distribution_auth(&parsed, &source)?;'
assert s.count(old) == 1
p.write_text(s.replace(old, 'let _ = (&parsed, &source);'))
PY
if timeout 300 cargo test -p ramflux-sdk --lib "$named" >"$log_file" 2>&1; then
    cat "$log_file"
    echo 'group_snapshot_seed mutant survived' >&2
    exit 1
fi
if ! rg -q "$named .*FAILED|$named --- FAILED" "$log_file"; then
    cat "$log_file"
    echo 'mutant did not reach the named assertion' >&2
    exit 1
fi
echo GROUP_SNAPSHOT_SEED_BTF_OK
