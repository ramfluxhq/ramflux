set -euo pipefail
cd "$(dirname "$0")/.."
source_file=crates/ramflux-sdk/src/client/routed/generated_receive.rs
named=read_model_serves_page_changes_and_detail_from_the_durable_store
snapshot=$(mktemp)
log_file=$(mktemp)
cp "$source_file" "$snapshot"
restore() { cp "$snapshot" "$source_file"; rm -f "$snapshot" "$log_file"; }
trap restore EXIT
python3 - "$source_file" <<'PY'
from pathlib import Path
import sys
p = Path(sys.argv[1]); s = p.read_text()
old = '''self.journal_generated_receive_updates(&opened.body)?;'''
assert s.count(old) == 1
p.write_text(s.replace(old, '''if false { self.journal_generated_receive_updates(&opened.body)?; }'''))
PY
if timeout 300 cargo test -p ramflux-sdk --lib "$named" >"$log_file" 2>&1; then
    cat "$log_file"
    echo 'LIVE_UPDATE_CURSOR mutant survived' >&2
    exit 1
fi
if ! rg -q "$named .*FAILED|$named --- FAILED" "$log_file"; then
    cat "$log_file"
    echo 'mutant did not reach the named assertion' >&2
    exit 1
fi
echo LIVE_UPDATE_CURSOR_BTF_OK
